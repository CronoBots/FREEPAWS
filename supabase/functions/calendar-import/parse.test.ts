import { assertEquals } from "jsr:@std/assert@1";

import { parseBusy } from "./parse.ts";

const ICS = `BEGIN:VCALENDAR
VERSION:2.0
BEGIN:VTIMEZONE
TZID:Europe/Brussels
BEGIN:DAYLIGHT
TZOFFSETFROM:+0100
TZOFFSETTO:+0200
DTSTART:19700329T020000
RRULE:FREQ=YEARLY;BYMONTH=3;BYDAY=-1SU
END:DAYLIGHT
BEGIN:STANDARD
TZOFFSETFROM:+0200
TZOFFSETTO:+0100
DTSTART:19701025T030000
RRULE:FREQ=YEARLY;BYMONTH=10;BYDAY=-1SU
END:STANDARD
END:VTIMEZONE
BEGIN:VEVENT
UID:a
DTSTART;TZID=Europe/Brussels:20261015T100000
DTEND;TZID=Europe/Brussels:20261015T113000
SUMMARY:Rendez-vous
END:VEVENT
BEGIN:VEVENT
UID:b
DTSTART;VALUE=DATE:20261020
DTEND;VALUE=DATE:20261021
SUMMARY:Journée entière
END:VEVENT
BEGIN:VEVENT
UID:c
DTSTART;TZID=Europe/Brussels:20261012T180000
DTEND;TZID=Europe/Brussels:20261012T190000
RRULE:FREQ=WEEKLY;COUNT=3
END:VEVENT
BEGIN:VEVENT
UID:d
DTSTART:20261016T090000Z
DTEND:20261016T100000Z
TRANSP:TRANSPARENT
END:VEVENT
BEGIN:VEVENT
UID:e
DTSTART:20261017T090000Z
DTEND:20261017T100000Z
STATUS:CANCELLED
END:VEVENT
END:VCALENDAR`;

Deno.test("plages occupées : fuseau, journée entière, récurrence, libres et annulés ignorés", () => {
  const busy = parseBusy(ICS, new Date("2026-10-07T12:00:00Z"));
  assertEquals(busy, [
    { start: "2026-10-15T08:00:00.000Z", end: "2026-10-15T09:30:00.000Z" },
    { start: "2026-10-19T22:00:00.000Z", end: "2026-10-20T22:00:00.000Z" },
    { start: "2026-10-12T16:00:00.000Z", end: "2026-10-12T17:00:00.000Z" },
    { start: "2026-10-19T16:00:00.000Z", end: "2026-10-19T17:00:00.000Z" },
    // Après le passage à l'heure d'hiver (25 octobre) : 18 h à Bruxelles = 17 h UTC.
    { start: "2026-10-26T17:00:00.000Z", end: "2026-10-26T18:00:00.000Z" },
  ]);
});
